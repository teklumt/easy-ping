// Writes the agent skill to skills/easy-ping/ at the repository root, from src/lib/skill.ts and
// src/lib/prompts.ts, so the skill says exactly what the copy buttons and llms-full.txt say.
//
// The output is committed (agents install skills straight from the repository), and it carries
// no version number, so a release does not leave it stale. `--check` fails when the committed
// files differ from what this script would write; CI runs it.

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  API_CONTEXT,
  MONGO_DETAILS,
  PLUGIN_DETAILS,
  REACT_NATIVE_DETAILS,
  TELEGRAM_DETAILS,
  WEB_PUSH_DETAILS,
} from "../src/lib/prompts.ts";
import { SKILL_BODY, SKILL_DESCRIPTION, SKILL_NAME, SKILL_REFERENCES } from "../src/lib/skill.ts";

const repo = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const out = join(repo, "skills", SKILL_NAME);

// Fenced as text: the source is plain-text layout, and Telegram's <b> and <a> must stay literal.
const fenced = (text) => `\`\`\`text\n${text.trim()}\n\`\`\``;

const reference = (title, intro, details) =>
  `# ${title}\n\n${intro} Read [api.md](api.md) first; this file adds what is specific to it.\n\n${fenced(details)}\n`;

const api = API_CONTEXT.replace(/^easy-ping v\S+ — /, "easy-ping — ");
if (api === API_CONTEXT) throw new Error("API_CONTEXT no longer starts with its version line");

const references = {
  "api.md": `# easy-ping API\n\nEvery option, route, adapter and plugin, and the rules that trip people up.\n\n${fenced(api)}\n`,
  "web-push.md": reference("Web push", "Browser push notifications.", WEB_PUSH_DETAILS),
  "telegram.md": reference("Telegram", "Telegram as a channel.", TELEGRAM_DETAILS),
  "react-native.md": reference(
    "React Native",
    "The inbox and native push in a React Native or Expo app. Both are in beta: say so.",
    REACT_NATIVE_DETAILS,
  ),
  "mongodb.md": reference("MongoDB", "Running easy-ping on MongoDB.", MONGO_DETAILS),
  "writing-a-plugin.md": reference(
    "Writing a plugin",
    "The plugin surface in detail.",
    PLUGIN_DETAILS,
  ),
};

const listed = SKILL_REFERENCES.map(([file]) => file).sort();
if (JSON.stringify(listed) !== JSON.stringify(Object.keys(references).sort())) {
  throw new Error("SKILL_REFERENCES and the generated reference files disagree");
}

const skill = `---
name: ${SKILL_NAME}
description: ${JSON.stringify(SKILL_DESCRIPTION)}
license: MIT
---

${SKILL_BODY}${SKILL_REFERENCES.map(([file, what]) => `- [references/${file}](references/${file}): ${what}`).join("\n")}

<!-- Generated by docs/scripts/generate-skill.mjs from docs/src/lib/skill.ts and prompts.ts. Edit those, not this file. -->
`;

const files = { "SKILL.md": skill };
for (const [file, text] of Object.entries(references)) files[`references/${file}`] = text;

if (process.argv.includes("--check")) {
  const stale = [];
  for (const [file, text] of Object.entries(files)) {
    const current = await readFile(join(out, file), "utf8").catch(() => null);
    // A Windows checkout with core.autocrlf has CRLF on disk and LF in the repository.
    if (current?.replace(/\r\n/g, "\n") !== text) stale.push(file);
  }
  const onDisk = await readdir(join(out, "references")).catch(() => []);
  for (const file of onDisk)
    if (!(`references/${file}` in files)) stale.push(`references/${file} (not generated)`);
  if (stale.length) {
    console.error(`skills/${SKILL_NAME} is out of date: ${stale.join(", ")}`);
    console.error("Run `pnpm --filter easy-ping-docs generate-skill` and commit the result.");
    process.exit(1);
  }
  console.log(`skills/${SKILL_NAME} is up to date`);
} else {
  await rm(join(out, "references"), { recursive: true, force: true });
  await mkdir(join(out, "references"), { recursive: true });
  for (const [file, text] of Object.entries(files)) await writeFile(join(out, file), text);
  console.log(`generated skills/${SKILL_NAME} (${Object.keys(files).length} files)`);
}
